-- Always Encrypted Setup for HIPAA PHI Protection
-- Run this AFTER the initial EF Core migration creates tables.
-- Requires SQL Server Enterprise or Azure SQL (Standard+ tier).
--
-- Prerequisites:
--   1. Column Master Key (CMK) created in Azure Key Vault or cert store
--   2. SQL Server has access to the CMK (via service principal or managed identity)
--
-- This script:
--   1. Creates the CMK metadata in SQL Server (points to external key store)
--   2. Creates Column Encryption Keys (CEK) encrypted by the CMK
--   3. Encrypts PHI columns with appropriate encryption type
--
-- Encryption types:
--   DETERMINISTIC: allows equality comparisons, indexes, JOINs (less secure)
--   RANDOMIZED: maximum security, no server-side operations (more secure)

-- ─── Step 1: Column Master Key (points to Azure Key Vault) ──────────────────
-- Replace the KEY_PATH with your actual Key Vault URI
CREATE COLUMN MASTER KEY [CMK_ClinicPhi]
WITH (
    KEY_STORE_PROVIDER_NAME = 'AZURE_KEY_VAULT',
    KEY_PATH = 'https://clinic-keyvault.vault.azure.net/keys/ClinicPhiMasterKey/version'
);
GO

