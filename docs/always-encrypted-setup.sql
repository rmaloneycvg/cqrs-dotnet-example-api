-- ─── Step 2: Column Encryption Keys ─────────────────────────────────────────
-- CEK for deterministic encryption (queryable fields)
CREATE COLUMN ENCRYPTION KEY [CEK_Deterministic]
WITH VALUES (
    COLUMN_MASTER_KEY = [CMK_ClinicPhi],
    ALGORITHM = 'RSA_OAEP',
    ENCRYPTED_VALUE = 0x... -- Generated by SSMS/PowerShell tooling
);
GO

-- CEK for randomized encryption (maximum security fields)
CREATE COLUMN ENCRYPTION KEY [CEK_Randomized]
WITH VALUES (
    COLUMN_MASTER_KEY = [CMK_ClinicPhi],
    ALGORITHM = 'RSA_OAEP',
    ENCRYPTED_VALUE = 0x... -- Generated by SSMS/PowerShell tooling
);
GO

-- ─── Step 3: Encrypt PHI Columns ─────────────────────────────────────────────
-- NOTE: In production, use SSMS Always Encrypted Wizard or PowerShell
-- Set-SqlColumnEncryption cmdlet. These ALTER statements show the intent.

-- Patients: Deterministic (supports unique index on Email)
ALTER TABLE Patients
ALTER COLUMN Email NVARCHAR(255) COLLATE Latin1_General_BIN2
ENCRYPTED WITH (
    COLUMN_ENCRYPTION_KEY = [CEK_Deterministic],
    ENCRYPTION_TYPE = DETERMINISTIC,
    ALGORITHM = 'AEAD_AES_256_CBC_HMAC_SHA_256'
) NOT NULL;
GO

